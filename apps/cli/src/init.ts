import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * `rutekit init` — writing the `.env` an operator would otherwise write by hand.
 *
 * The whole reason this command exists is one line in `.env.example`:
 *
 *     # Generate: bun -e "console.log(crypto.randomBytes(32).toString('hex'))"
 *
 * Two secrets have to be 32 random bytes in hex, and the failure mode of getting
 * them wrong is not a crash — it is an instance that stores credentials under a
 * key nobody wrote down, or one whose password hash has no pepper. Both are
 * discovered much later, if at all. So the CLI generates them.
 *
 * **Nothing is overwritten without `--force`.** An `.env` holds the encryption key
 * for every stored credential, and regenerating it silently would make every one
 * of them unreadable — the data would still be there and would never decrypt
 * again. That is the one mistake in this file that cannot be undone, so it is the
 * one the command refuses to make.
 */

/** The two secrets, and what a wrong one costs. */
const SECRETS: readonly { readonly name: string; readonly note: string }[] = [
  {
    name: 'RUTEKIT_ENCRYPTION_KEY',
    note: '32 bytes of hex, encrypting every stored provider credential. Lose it and they are unrecoverable.',
  },
  {
    name: 'RUTEKIT_AUTH_SECRET',
    note: 'Argon2id pepper for the console password. Changing it invalidates the stored hash.',
  },
];

export interface InitResult {
  readonly ok: boolean;
  /** Why it refused, when it did. */
  readonly reason: string | null;
  readonly path: string;
}

export interface InitOptions {
  /** The directory to write into. Defaults to the working directory. */
  readonly cwd: string;
  readonly force: boolean;
  /** Injectable, so a test does not write random bytes into its assertions. */
  readonly generate?: () => string;
}

export function generateSecret(): string {
  return randomBytes(32).toString('hex');
}

/** The file's contents, as a function of the two secrets and nothing else. */
export function envFile(secret: string, authSecret: string): string {
  return `# rutekit — generated by \`rutekit init\`.
#
# Every value here is a secret. Do not commit this file, and do not lose the
# first one: RUTEKIT_ENCRYPTION_KEY is what makes the stored credentials
# readable, and an instance started without it cannot decrypt them.

# ── Secrets ──────────────────────────────────────────────────
RUTEKIT_ENCRYPTION_KEY=${secret}
RUTEKIT_AUTH_SECRET=${authSecret}

# ── Server ───────────────────────────────────────────────────
# Keep on loopback unless you know why you are exposing it.
RUTEKIT_HOST=127.0.0.1
RUTEKIT_PORT=7331

# ── Storage ──────────────────────────────────────────────────
RUTEKIT_DATABASE_URL=./data/rutekit.sqlite
RUTEKIT_DATA_DIR=./data

# ── Optional ─────────────────────────────────────────────────
# A local ComfyUI lives on a private address, which the egress guard refuses by
# default. Uncomment to let Studio render with it.
# RUTEKIT_EGRESS_ALLOWLIST=127.0.0.1/32
# Node binary for the automation subprocess, when \`node\` is not on PATH.
# RUTEKIT_NODE_BINARY=
# Captcha assist for automation. Manual assist works without it.
# RUTEKIT_CAPSOLVER_KEY=
`;
}

export function init(options: InitOptions): InitResult {
  const path = join(options.cwd, '.env');
  const generate = options.generate ?? generateSecret;

  if (existsSync(path) && !options.force) {
    return {
      ok: false,
      path,
      reason:
        'A .env already exists. Overwriting it would replace the key your stored credentials are encrypted with, and they would never decrypt again. Pass --force only if you are certain.',
    };
  }

  writeFileSync(path, envFile(generate(), generate()), { encoding: 'utf8', mode: 0o600 });
  return { ok: true, path, reason: null };
}

/** Whether an existing `.env` already carries a usable encryption key. */
export function hasEncryptionKey(path: string): boolean {
  if (!existsSync(path)) return false;
  const match = /^RUTEKIT_ENCRYPTION_KEY=(.+)$/m.exec(readFileSync(path, 'utf8'));
  return match?.[1] !== undefined && match[1].trim() !== '';
}

export { SECRETS };
