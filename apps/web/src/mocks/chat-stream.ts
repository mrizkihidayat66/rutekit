import type { ChatMessageMeta, FinishReason } from '@contracts';

import { planChatReply, type ChatReplyPlan } from './fixtures/chat-replies.ts';
import { words, type SseBeat } from './sse.ts';

/**
 * Turn a reply plan into the frames a model would emit.
 *
 * This is the piece that makes the mock a *protocol* rather than a canned body:
 * the page does not know it is talking to a mock, because what it receives is a
 * well-formed AI SDK UI Message stream with the same chunk order the real
 * backend will produce. The order matters and is not arbitrary —
 *
 *   start → reasoning-start → reasoning-delta… → reasoning-end
 *         → text-start → text-delta… → text-end
 *         → tool-input-start → tool-input-available
 *         → finish → [DONE]
 *
 * — because the client throws if a delta arrives without its start frame, and
 * because a renderer that sees the answer before the deliberation would put the
 * thinking block in the wrong place.
 *
 * Metadata is split across `start` and `finish` on purpose. The client merges
 * partial `messageMetadata`, so `start` carries what is known before the first
 * token (which model answered) and `finish` carries what is only known after
 * the last one (how many tokens, and how fast).
 */

/** Held before the first frame. Long enough to see the typing state, short enough not to annoy. */
const TTFT_MS = 260;

/** Per-word pacing. A long answer streams faster so it does not outstay its welcome. */
function wordDelay(count: number): number {
  if (count > 140) return 6;
  if (count > 60) return 12;
  return 20;
}

/** A deliberation that takes a beat longer than an answer word, so it reads as slower. */
const REASONING_WORD_MS = 26;

export interface ChatTurnOptions {
  readonly prompt: string;
  readonly hasImage: boolean;
  readonly thinkingLevel: string;
  readonly providerId: string | null;
  readonly model: string | null;
  /** Generated by the handler so the persisted message and the stream agree. */
  readonly messageId: string;
}

function meta(partial: Partial<ChatMessageMeta>): ChatMessageMeta {
  return {
    ttftMs: null,
    totalMs: null,
    tokensPerSecond: null,
    usage: null,
    finishReason: null,
    providerId: null,
    model: null,
    ...partial,
  };
}

export interface ChatTurn {
  readonly beats: SseBeat[];
  readonly plan: ChatReplyPlan;
  /** The same metadata the `finish` frame carries, for the handler to persist. */
  readonly meta: ChatMessageMeta;
}

export function chatTurn(options: ChatTurnOptions): ChatTurn {
  const plan = planChatReply({
    prompt: options.prompt,
    hasImage: options.hasImage,
    thinkingLevel: options.thinkingLevel,
  });

  const beats: SseBeat[] = [
    {
      after: TTFT_MS,
      chunk: {
        type: 'start',
        messageId: options.messageId,
        messageMetadata: meta({ providerId: options.providerId, model: options.model }),
      },
    },
  ];

  const textWords = words(plan.text);
  const reasoningWords = plan.reasoning === null ? [] : words(plan.reasoning);
  const reasoningId = 'rsn_1';
  const textId = 'txt_1';

  let elapsed = TTFT_MS;
  const step = (after: number): number => {
    elapsed += after;
    return after;
  };

  if (plan.reasoning !== null) {
    beats.push({ after: step(0), chunk: { type: 'reasoning-start', id: reasoningId } });
    for (const word of reasoningWords) {
      beats.push({
        after: step(REASONING_WORD_MS),
        chunk: { type: 'reasoning-delta', id: reasoningId, delta: word },
      });
    }
    beats.push({ after: step(0), chunk: { type: 'reasoning-end', id: reasoningId } });
  }

  beats.push({ after: step(0), chunk: { type: 'text-start', id: textId } });
  for (const word of textWords) {
    beats.push({
      after: step(wordDelay(textWords.length)),
      chunk: { type: 'text-delta', id: textId, delta: word },
    });
  }
  beats.push({ after: step(0), chunk: { type: 'text-end', id: textId } });

  if (plan.toolCall !== null) {
    const toolCallId = 'call_1';
    beats.push({
      after: step(60),
      chunk: { type: 'tool-input-start', toolCallId, toolName: plan.toolCall.name },
    });
    beats.push({
      after: step(120),
      chunk: { type: 'tool-input-available', toolCallId, toolName: plan.toolCall.name, input: plan.toolCall.input },
    });
  }

  const outputTokens = Math.max(1, Math.round((plan.text.length + (plan.reasoning?.length ?? 0)) / 4));
  const inputTokens = Math.max(1, Math.round(options.prompt.length / 4));
  const totalMs = elapsed + 40;
  const streamedMs = Math.max(1, totalMs - TTFT_MS);

  const finalMeta = meta({
    ttftMs: TTFT_MS,
    totalMs,
    tokensPerSecond: Math.round((outputTokens / streamedMs) * 1000 * 10) / 10,
    usage: {
      inputTokens,
      outputTokens,
      cachedInputTokens: 0,
      reasoningTokens: Math.max(0, Math.round((plan.reasoning?.length ?? 0) / 4)),
      totalTokens: inputTokens + outputTokens,
    },
    finishReason: plan.finishReason,
    providerId: options.providerId,
    model: options.model,
  });

  beats.push({
    after: step(40),
    chunk: {
      type: 'finish',
      finishReason: wireFinishReason(plan.finishReason),
      messageMetadata: finalMeta,
    },
  });

  return { beats, plan, meta: finalMeta };
}

/**
 * The contract spells these with underscores; the wire spells them with hyphens.
 *
 * They are two vocabularies for the same fact and the mapping is not the
 * identity, which is exactly the kind of thing that silently produces an
 * unmapped state three layers down if it is left implicit.
 */
function wireFinishReason(reason: FinishReason): string {
  switch (reason) {
    case 'tool_calls':
      return 'tool-calls';
    case 'content_filter':
      return 'content-filter';
    case 'stop':
    case 'length':
    case 'error':
    case 'aborted':
      return reason;
  }
}
