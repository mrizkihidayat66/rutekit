import type { ProviderCategory, WireFamily } from '@contracts';

/**
 * The curated provider set the v1 catalog ships (FR-2.1). Model ids are the
 * real ones so the mock looks like the product rather than like a placeholder —
 * a screenshot of `gpt-4o-mini` beside `claude-3-5-sonnet` reads as a router,
 * and `model-a` beside `model-b` does not.
 */
export interface ModelSeed {
  id: string;
  displayName?: string;
  contextK?: number;
  maxOutputK?: number;
  vision?: boolean;
  tools?: boolean;
  reasoning?: boolean;
  embedding?: boolean;
  /** USD per million tokens. */
  inputPrice?: number;
  outputPrice?: number;
  deprecated?: boolean;
}

export interface ProviderCapabilities {
  quota: boolean;
  oauth: boolean;
  automation: boolean;
  streaming: boolean;
  vision: boolean;
  tools: boolean;
}

export interface ProviderSeed {
  id: string;
  name: string;
  description: string;
  category: ProviderCategory;
  wireFamily: WireFamily;
  icon: string;
  baseUrl: string | null;
  docsUrl: string | null;
  freeTier: boolean;
  capabilities: ProviderCapabilities;
  /** Weights bias the status roll; `ready` dominates for a healthy instance. */
  healthBias?: 'good' | 'mixed' | 'poor';
  models: readonly ModelSeed[];
}

